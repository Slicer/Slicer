setup_colors() {
  if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
    C_BLUE=$(printf '\033[1;34m'); C_YELLOW=$(printf '\033[1;33m')
    C_RED=$(printf '\033[1;31m'); C_GREEN=$(printf '\033[1;32m')
